
package eva2_22_incrementos;


public class EVA2_22_INCREMENTOS {

   public static void main(String[] args) {

      int i = 1;
      
      //ACUMULADOR
      //YO QUIERO QUE LA I SE INCREMENTE EN 1
      System.out.println("i= " + i);
      i =i + 1; // acumulador
      
      System.out.println("i= " + i);
      i =i + 1; // acumulador
      
      System.out.println("i= " + i);
     
      i++; //incremetna en uno el valor de la variable
      System.out.println("i= " + i);
     
      i+=2; //incremetna en 1 el valor de la variable
      System.out.println("i= " + i);
      
      i--; //incremetna en uno el valor de la variable
      System.out.println("i= " + i);
      
      i-=2; //incremetna en uno el valor de la variable
      System.out.println("i= " + i);
      
      i*=2; //incremetna en uno el valor de la variable
      System.out.println("i= " + i);
   }
   
}
